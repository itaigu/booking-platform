export function translateError(message: string, lang: Lang): string {
  for (const [re, text] of lang === "es" ? errorsEs : errorsEn) {
    const m = message.match(re);
    if (m) return message.replace(/^[\s\S]*$/, () => text.replace(/\$(\d)/g, (_, n) => m[Number(n)]));
  }
  return message;
}
